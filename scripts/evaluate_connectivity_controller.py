"""Evaluate a final connectivity controller on saved or user specified routes."""
import argparse
import json
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from uav_joint_optimization.experiment_env import RadioMap
from uav_joint_optimization.connectivity_env import ConnectivityConfig
from uav_joint_optimization.connectivity_ppo import HybridPolicy, evaluate, summarize


def main():
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--controller", choices=["straight_rss", "straight_radio", "joint_mpc", "joint_lookahead"])
    group.add_argument("--checkpoint", type=Path)
    parser.add_argument("--split", default="test", choices=["validation", "validation_longer", "test", "longer_test"])
    parser.add_argument("--start", type=float, nargs=2)
    parser.add_argument("--goal", type=float, nargs=2)
    parser.add_argument("--output", type=Path, default=ROOT / "outputs/connectivity_evaluation")
    args = parser.parse_args()
    if bool(args.start) != bool(args.goal):
        parser.error("Provide both --start and --goal")
    policy = None
    config = ConnectivityConfig(**json.loads((ROOT / "configs/frozen_connectivity_v2.json").read_text())["environment"])
    if args.checkpoint:
        # Only load trusted checkpoints generated by this project.
        checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=False)
        assert checkpoint["metadata"]["environment"] == config.__dict__
        policy = HybridPolicy(checkpoint["obs_dim"], checkpoint["hidden"])
        policy.load_state_dict(checkpoint["policy"])
        policy.eval()
    if args.start:
        for point in (args.start, args.goal):
            if not (0 <= point[0] <= 5000 and 0 <= point[1] <= 3500):
                parser.error("Route endpoints must lie within the 5000 by 3500 m map")
        routes = [{"id": "user_route", "start": args.start, "goal": args.goal, "load_phase": 0}]
    else:
        routes = json.loads((ROOT / "configs/connectivity_scenarios_v2.json").read_text())[args.split]
    torch.set_num_threads(2)
    radio = RadioMap(ROOT / "dataset/Barcelona_dataset_January.h5")
    rows = evaluate(policy, radio, routes, config, args.output, pd=args.controller or False)
    print(json.dumps(summarize(rows), indent=2))


if __name__ == "__main__":
    main()
