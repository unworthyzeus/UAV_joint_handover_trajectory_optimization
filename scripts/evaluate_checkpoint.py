"""Replay a locally generated policy on saved scenarios or a specified route."""
import argparse
import json
import sys
from pathlib import Path
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from uav_joint_optimization.experiment_env import EnvironmentConfig, RadioMap
from uav_joint_optimization.experiment_ppo import HybridPolicy, evaluate, summarize


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--split", choices=["validation", "test", "longer_test"], default="test")
    p.add_argument("--start", nargs=2, type=float)
    p.add_argument("--goal", nargs=2, type=float)
    p.add_argument("--output", type=Path, default=ROOT/"outputs/checkpoint_evaluation")
    args=p.parse_args()
    if bool(args.start) != bool(args.goal):
        p.error("Provide both --start and --goal")
    # Only use checkpoints generated by this project or another trusted source.
    checkpoint=torch.load(args.checkpoint, map_location="cpu", weights_only=False)
    policy=HybridPolicy(checkpoint["obs_dim"], checkpoint["hidden"])
    policy.load_state_dict(checkpoint["policy"]); policy.eval()
    torch.set_num_threads(2)
    config=EnvironmentConfig(**checkpoint["metadata"]["environment"])
    radio=RadioMap(ROOT/"dataset/Barcelona_dataset_January.h5")
    if args.start:
        scenarios=[{"id":"user_route", "start":args.start,"goal":args.goal,"load_phase":0}]
    else:
        scenarios=json.loads((ROOT/"configs/controlled_scenarios.json").read_text())[args.split]
    rows=evaluate(policy,radio,scenarios,config,args.output)
    print(json.dumps(summarize(rows),indent=2))


if __name__=="__main__":
    main()
